#!/usr/bin/env python3
"""Bake a WAV clip into block RAM for the BTN1 alarm player.

Writes rtl/alarm_rom.mem (hex samples for $readmemh) and rtl/alarm_rom.sv
(the ROM module, with the clip length). Both are generated and ignored by Git,
since the source clip may not be ours to redistribute.

The clip is stored as 16 kHz, signed 8-bit mono: 5.6 s is ~89 KB, about 40%
of the Cmod A7-35T's block RAM. Full 48 kHz 16-bit would not fit.

    python3 scripts/gen_alarm_rom.py C:/Windows/Media/Alarm01.wav
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from send_audio import load_wav, resample  # noqa: E402

RATE = 16_000
ADDR_BITS = 17                 # matches alarm_player; 2^17 samples = 8.2 s
MAX_SAMPLES = 2 ** ADDR_BITS
RTL = Path(__file__).resolve().parent.parent / "rtl"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("wav", help="WAV file (any rate/channels)")
    ap.add_argument("--volume", type=float, default=0.25,
                    help="linear gain after normalizing the clip's peak to full scale (default 0.25)")
    args = ap.parse_args()

    x, rate = load_wav(args.wav)
    x = resample(x, rate, RATE)
    if not x:
        sys.exit("empty clip")
    if len(x) > MAX_SAMPLES:
        print(f"clip is {len(x) / RATE:.2f} s; truncating to {MAX_SAMPLES / RATE:.2f} s")
        x = x[:MAX_SAMPLES]

    peak = max(abs(v) for v in x) or 1.0
    gain = args.volume / peak
    samples = [max(-128, min(127, round(v * gain * 127))) for v in x]

    (RTL / "alarm_rom.mem").write_text("".join(f"{s & 0xFF:02x}\n" for s in samples))
    (RTL / "alarm_rom.sv").write_text(f"""\
// Generated by scripts/gen_alarm_rom.py from {Path(args.wav).name} -- do not edit.
// {len(samples)} samples of signed 8-bit audio at {RATE} Hz, read from alarm_rom.mem.
module alarm_rom (
    input  logic                  clk,
    input  logic [{ADDR_BITS - 1}:0]         addr,
    output logic signed [7:0]     data,   // valid one clock after addr
    output logic [{ADDR_BITS - 1}:0]         last    // address of the final sample
);
  localparam int LEN = {len(samples)};
  logic [7:0] mem[LEN];                   // inferred as block RAM
  initial $readmemh("alarm_rom.mem", mem);
  always_ff @(posedge clk) data <= mem[addr];
  assign last = {ADDR_BITS}'(LEN - 1);
endmodule
""")
    print(f"{len(samples)} samples, {len(samples) / RATE:.2f} s at {RATE} Hz -> {RTL / 'alarm_rom.mem'}")


if __name__ == "__main__":
    main()
